#!/usr/bin/env python3
"""Build the TALLOW interface marks and surfaces as PNGs with a provenance chunk.

  python3 build_icons.py            -> Raster/T_*.png, Review/contact-*.png

All pixels come from engrave.py / marks.py (hand-placed vector paths cut as white-line
engraving) and surfaces.py (procedural soot grounds). Nothing is sampled or traced.
"""
import datetime
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import marks                      # noqa: E402
import surfaces                   # noqa: E402
from engrave import Plate         # noqa: E402

RASTER = HERE / 'Raster'
STAMP = datetime.date.today().isoformat()


def provenance(name, how):
    return (f"TALLOW interface texture T_{name}. {how} Generated by Tools/FinalPass/icons/build_icons.py "
            f"(engrave.py, marks.py, surfaces.py) with numpy and pycairo on {STAMP}. "
            "Vector paths placed by hand in code; no photographs, scans, traced or model-generated pixels.")


# name: (draw function, width px, height px, design width, optical size at 1080p)
ITEMS = {
    'Candle':       (lambda p, o: marks.candle_mark(p, o, 1.0, 'lit'), 256, 256, 108),
    'CandleOut':    (lambda p, o: marks.candle_mark(p, o, .62, 'out'), 256, 256, 108),
    'Matches':      (marks.matches_mark, 256, 256, 108),
    'Crowbar':      (marks.crowbar_mark, 256, 256, 108),
    'Fuse':         (marks.fuse_mark, 256, 256, 108),
    'Reel':         (marks.reel_mark, 256, 256, 108),
    'Map':          (marks.map_mark, 256, 256, 108),
    'Book':         (marks.book_mark, 256, 256, 108),
    'Letter':       (marks.letter_mark, 256, 256, 108),
    'Cutting':      (marks.cutting_mark, 256, 256, 108),
    'Photo':        (marks.photo_mark, 256, 256, 108),
    'Sewing':       (marks.sewing_mark, 256, 256, 108),
    'Drawing':      (marks.drawing_mark, 256, 256, 108),
    'Breath':       (marks.breath_mark, 256, 256, 108),
    'Eye':          (marks.eye_mark, 256, 256, 108),
    'Ear':          (marks.ear_mark, 256, 256, 108),
    'Heart':        (marks.heart_mark, 256, 256, 108),
}
SMALL = {
    'BreathSmall':  (marks.breath_mark, 128, 128, 34),
    'WaxFull':      (marks.wax_mark('Full'), 128, 208, 40),
    'WaxMedium':    (marks.wax_mark('Medium'), 128, 208, 40),
    'WaxLow':       (marks.wax_mark('Low'), 128, 208, 40),
    'WaxGutter':    (marks.wax_mark('Gutter'), 128, 208, 40),
    'WaxOut':       (marks.wax_mark('Out'), 128, 208, 40),
    'Key':          (marks.key_mark, 96, 96, 34),
}


def build():
    RASTER.mkdir(exist_ok=True)
    built = {}
    for table in (ITEMS, SMALL):
        for i, (name, (fn, w, h, o)) in enumerate(table.items()):
            p = Plate(w, h, design_w=100.0, seed=17 + i)
            fn(p, o)
            how = f"A white-line engraving of the mark, cut for a {o} px optical size."
            built[name] = p.save(RASTER / f'T_{name}.png', provenance(name, how), grain_amt=.16 if o > 60 else .10)
    for name, img, how in surfaces.build_all():
        surfaces.save(img, RASTER / f'T_{name}.png', provenance(name, how))
        built[name] = img
    return built


if __name__ == '__main__' and '--pad' not in sys.argv:
    built = build()
    for n in sorted(built):
        print(n, built[n].size)



def build_pad():
    import pad
    folder = RASTER / 'Pad'
    folder.mkdir(parents=True, exist_ok=True)
    out = {}
    for i, (name, (fn, w, h, o)) in enumerate(pad.GLYPHS.items()):
        p = Plate(w, h, design_w=100.0 * w / max(w, h) if w > h else 100.0, seed=91 + i)
        fn(p, o)
        out[name] = p.save(folder / f'T_{name}.png', provenance(name, 'A DualSense button glyph cut in the interface hand.'), grain_amt=.10)
    return out


if __name__ == '__main__' and '--pad' in sys.argv:
    for n, img in build_pad().items():
        print(n, img.size)
