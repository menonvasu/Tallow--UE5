"""The TALLOW title wordmark as a white-line engraving in tallow ivory, on a transparent ground.

Set in IM FELL French Canon capitals with open tracking. Each letter is treated as a low relief
cut in soot: its face is engraved in horizontal lines whose width swells where the relief turns
to the candle (upper left) and thins to a hair where it turns away, the way the interface marks
are cut (Tools/FinalPass/icons/engrave.py). A crisp contour holds the letter, heavier on the lit
edges. The line pitch is set so the cuts still read as lines at 900 px wide and merge into a
clean engraved tone at 560 px. Pure numpy and Pillow from the font's outlines.

    python3 wordmark.py      -> out/Wordmark.png (2400x640 RGBA), out/Wordmark_preview.png
"""
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

import look

HERE = Path(__file__).resolve().parent
OUT = HERE / 'out'
FONT = str(HERE / 'fonts' / 'IMFeFCrm28P.ttf')
W, H, SS = 2400, 640, 3
TEXT = 'TALLOW'
LIGHT = np.array([-.55, -.62, .56])
LIGHT = LIGHT / np.linalg.norm(LIGHT)
PITCH = 11.0          # px at 2400 wide between engraved lines


def letters_mask():
    """The letters at SS x, tracked open, centred, optically sized to the canvas."""
    w, h = W * SS, H * SS
    size = int(560 * SS)
    f = ImageFont.truetype(FONT, size)
    track = .16 * size
    adv = [f.getlength(c) for c in TEXT]
    total = sum(adv) + track * (len(TEXT) - 1)
    # fit: leave a margin either side
    if total > w * .9:
        size = int(size * w * .9 / total)
        f = ImageFont.truetype(FONT, size)
        track = .16 * size
        adv = [f.getlength(c) for c in TEXT]
        total = sum(adv) + track * (len(TEXT) - 1)
    img = Image.new('L', (w, h), 0)
    d = ImageDraw.Draw(img)
    x = (w - total) / 2
    asc = f.getbbox('T', anchor='ls')
    cap = -asc[1]
    base = h / 2 + cap / 2
    for c, a in zip(TEXT, adv):
        d.text((x, base), c, font=f, fill=255, anchor='ls')
        x += a + track
    return np.asarray(img, np.float32) / 255.0


def engrave():
    M = letters_mask()
    h, w = M.shape
    # the relief: a rounded bevel rising from the edge, so every stroke has a lit and a shaded side
    r = 9 * SS
    hgt = look.blur(M, r) * M
    gy, gx = np.gradient(hgt)
    k = r * 1.4
    n = np.dstack([-gx * k, -gy * k, np.ones_like(M)])
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    lit = np.clip(n @ LIGHT, 0, 1)
    lit = np.clip((lit - .3) / .55, 0, 1) ** 1.25
    # the engraved lines: width carries the light; a slow tremor keeps them cut by hand
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    rng = np.random.default_rng(1974)
    wob = look.blur(rng.normal(0, 1, (h // 64 + 2, w // 64 + 2)).astype(np.float32), 1)
    wob = np.asarray(Image.fromarray(wob, 'F').resize((w, h), Image.BICUBIC), np.float32)[:h, :w]
    p = PITCH * SS
    phase = ((yy + wob * .5 * SS) % p) / p - .5            # -0.5..0.5 across a line
    half = .5 * (.1 + .86 * lit)                             # fraction of the pitch inked
    aa = 1.2 / p
    lines = np.clip((half - np.abs(phase)) / aa, 0, 1)
    # the contour: crisp, heavier where the edge faces the candle
    inner = look.blur(M, 1.6 * SS)
    edge_n = np.dstack([gx, gy])
    en = np.linalg.norm(edge_n, axis=-1) + 1e-6
    facing = np.clip(-(gx * LIGHT[0] + gy * LIGHT[1]) / en, -1, 1)
    band = (2.0 + 1.6 * (facing * .5 + .5)) * SS
    depth = (1 - look.blur(M, 1.2 * band.mean())) * M
    contour = np.clip((M - inner) * 4.0, 0, 1) * M
    contour = np.maximum(contour, np.clip((.5 - np.abs(look.blur(M, band.mean() * .35) - .5)) * 3.5, 0, 1) * M * (.35 + .55 * (facing * .5 + .5)))
    a = np.clip(np.maximum(lines * M, contour), 0, 1)
    # a hair of ink spread, then down to size
    a = np.clip(look.blur(a, 1) * 1.04, 0, 1)
    a = a.reshape(H, SS, W, SS).mean((1, 3))
    # the cut breaks up a little at its thinnest
    g = look.value_noise(W, H, 77, 2)
    a = a * (1 - .18 * g * (1 - a))
    return np.clip(a, 0, 1)


def main():
    OUT.mkdir(exist_ok=True)
    a = engrave()
    rgb = np.broadcast_to(look.TALLOW, (H, W, 3))
    img = Image.fromarray((np.dstack([rgb, a]) * 255 + .5).astype(np.uint8), 'RGBA')
    prov = ('TALLOW title wordmark. Generated by Tools/FinalPass/ui/plates/wordmark.py (numpy, Pillow): the letters of '
            'IM FELL French Canon (Igino Marini, SIL OFL 1.1) cut as a white-line engraving, line width from a '
            'computed relief lit from the upper left. No sampled, traced or generated imagery.')
    look.save_png(img, OUT / 'Wordmark.png', prov)
    # preview: full size on the soot, then the two shipping sizes over a dark game-like ground
    pw, ph = 2400, 1600
    g = look.soot_ground(pw, ph, 31)
    yy, xx = np.mgrid[0:ph, 0:pw].astype(np.float32)
    warm = np.clip(1 - np.hypot(xx - 1900, yy - 1500) / 1500, 0, 1)[..., None] * np.array([.10, .06, .03])
    g = np.clip(g + warm, 0, 1)
    base = Image.fromarray((g * 255).astype(np.uint8), 'RGB').convert('RGBA')
    base.alpha_composite(img, (0, 40))
    for wpx, (x, y) in ((900, (80, 760)), (560, (1100, 900))):
        small = img.resize((wpx, int(wpx * H / W)), Image.LANCZOS)
        base.alpha_composite(small, (x, y))
    d = ImageDraw.Draw(base)
    f = ImageFont.truetype(str(HERE / 'fonts' / 'IMFellEnglish-Italic.ttf'), 28)
    d.text((80, 1150), '900 px (title plate)', font=f, fill=(148, 139, 122))
    d.text((1100, 1080), '560 px (menu)', font=f, fill=(148, 139, 122))
    base.convert('RGB').save(OUT / 'Wordmark_preview.png')
    print('built Wordmark')


if __name__ == '__main__':
    main()
