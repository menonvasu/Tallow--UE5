#!/usr/bin/env python3
"""Regenerate Source/Tallow/Audio/TallowCorruptedCues.inl from corrupted_cues.json.
usage: gen_cues.py <corrupted_cues.json> <out.inl>"""
import json, sys
src, out = sys.argv[1], sys.argv[2]
cues = json.load(open(src))['cues']
P = {'under': 'Under', 'seam': 'Seam', 'break': 'Break', 'after': 'After'}
def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
lines = ['// Generated by Tools/FinalPass/overlay/gen_cues.py from corrupted_cues.json. Do not edit.',
         '// Line, Group, Key, Start, Gap, Duration, Interrupt, Placement, MinPlaythrough, Asset, Subtitle']
for c in cues:
    lines.append('{TEXT(%s),TEXT(%s),TEXT(%s),%.3ff,%.3ff,%.3ff,%.3ff,ETallowCorruptPlacement::%s,%d,TEXT(%s),TEXT(%s)},' % (
        q(c['line_id']), q(c['cue_id']), q(c['recording_key']), c['start_seconds'], c['chain_gap'],
        c['est_duration'], c['interrupt_seconds'], P.get(c['placement'], 'Seam'), c['min_playthrough'],
        q(c['asset']), q(c['subtitle'])))
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(cues), 'cues')
