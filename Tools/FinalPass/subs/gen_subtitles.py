#!/usr/bin/env python3
"""Writes Source/Tallow/UI/Presentation/TallowSubtitleLines.inl: the words of every spoken line, by sound asset name.

Text is never invented. Sources, in the order they apply:
  Tools/Audio/VoicePass/script.json            narration, the papers read aloud, Nell and Maisie lines (by asset)
  Lore/VO/Mim/mim-lines.json                    the scripted Mim lines VO_Mim_* (my booth read)
  Tools/SoundRecorder/prompts.js + import-manifest.json   the 26 Oct Mim pool (V_Mim_*), the prompt Ty read
  Creature/Lines/lines.json                     my earlier creature lines V_Creature_NN (fallback pools)
Lines that are only a sound ("[A held breath]", "(giggle)") get no subtitle and are listed in the report.
Usage: gen_subtitles.py <tallow-source-root> [report.json]
"""
import json, os, re, subprocess, sys, tempfile

CUR = os.path.expanduser('~/Projects/tallow-current')
OUT = os.path.join(sys.argv[1], 'Tallow/Source/Tallow/UI/Presentation/TallowSubtitleLines.inl')

def clean(t):
    return re.sub(r'\s+', ' ', t).strip()

def sound_only(t):
    return re.fullmatch(r'[\[(].*[\])]', t) is not None

lines, silent = {}, []

def add(asset, text):
    text = clean(text)
    if not text:
        return
    if sound_only(text):
        silent.append([asset, text]); return
    lines[asset] = text

script = json.load(open(f'{CUR}/Tools/Audio/VoicePass/script.json'))
parts = {}
for c in script['cues']:
    parts.setdefault(c['asset'], []).append((c.get('part', 1), c['text']))
for asset, ps in parts.items():
    add(asset, ' '.join(t for _, t in sorted(ps)))

for l in json.load(open(f'{CUR}/Tallow/SourceAssets/Lore/VO/Mim/mim-lines.json'))['lines']:
    if l['file'].startswith('VO_Mim_'):
        add(l['file'], l['text'])

with tempfile.TemporaryDirectory() as tmp:
    shutil_src = f'{CUR}/Tools/SoundRecorder/prompts.js'
    open(f'{tmp}/p.mjs', 'w').write(open(shutil_src).read())
    open(f'{tmp}/d.mjs', 'w').write("import {mimCues} from './p.mjs'; console.log(JSON.stringify(mimCues));")
    cues = {c['id']: c for c in json.loads(subprocess.check_output(['node', f'{tmp}/d.mjs']))}
for a in json.load(open(f'{CUR}/Tools/Audio/VoicePass/import-manifest.json')):
    if a['name'].startswith('V_Mim_'):
        ids = [p['cue'] for p in a['parts']]
        if all(i in cues for i in ids):
            add(a['name'], ' '.join(cues[i]['text'] for i in ids))

for l in json.load(open(f'{CUR}/Tallow/SourceAssets/Audio/Recording/Creature/Lines/lines.json')):
    add(l['file'], l['text'])

def lit(s):
    o = ''
    for ch in s:
        if ch in '"\\': o += '\\' + ch
        elif ord(ch) > 126: o += '\\u%04X' % ord(ch)
        else: o += ch
    return o

with open(OUT, 'w') as f:
    f.write('// Generated by Tools/FinalPass/subs/gen_subtitles.py. Do not edit.\n// Sound asset, words\n')
    for k in sorted(lines):
        f.write('{TEXT("%s"),TEXT("%s")},\n' % (k, lit(lines[k])))
print(len(lines), 'lines;', len(silent), 'sound-only skipped')
if len(sys.argv) > 2:
    json.dump({'lines': len(lines), 'soundOnly': silent}, open(sys.argv[2], 'w'), indent=1)
